#!/usr/bin/env python3
"""Write src/usd/sdf/identifier_tables.rs: the XID_Start and XID_Continue
ranges (UAX #31) from U+0080 on, merged where adjacent, ASCII left to code,
from the Unicode Character Database's DerivedCoreProperties.txt.

Usage: tools/gen_identifiers.py <DerivedCoreProperties.txt>
(https://www.unicode.org/Public/<version>/ucd/DerivedCoreProperties.txt)"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1]).read_text(encoding='utf-8')
version = re.match(r'# DerivedCoreProperties-(\d+\.\d+\.\d+)\.txt', source)
if not version:
    sys.exit('not a DerivedCoreProperties.txt: its first line names no version')
version = version.group(1)


def ranges(prop):
    pairs = []
    for line in source.splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        codes, name = (part.strip() for part in line.split(';')[:2])
        if name != prop:
            continue
        first, _, last = codes.partition('..')
        pairs.append((int(first, 16), int(last or first, 16)))
    merged = []
    for a, b in sorted(pairs):
        if merged and a <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return [(max(a, 128), b) for a, b in merged if b >= 128]


def table(name, rows):
    lines = []
    for i in range(0, len(rows), 6):
        lines.append('    ' + ' '.join(f'({a}, {b}),' for a, b in rows[i:i + 6]))
    return f'pub(super) const {name}: &[(u32, u32)] = &[\n' + '\n'.join(lines) + '\n];\n'


out = ROOT / 'src/usd/sdf/identifier_tables.rs'
out.write_text(f'//! XID_Start and XID_Continue ranges from U+0080 on (Unicode {version},\n'
               '//! DerivedCoreProperties.txt), merged where adjacent. Generated by\n'
               '//! tools/gen_identifiers.py; do not edit.\n\n'
               '#[rustfmt::skip]\n' + table('START', ranges('XID_Start')) + '\n'
               '#[rustfmt::skip]\n' + table('CONTINUE', ranges('XID_Continue')))
print(f'wrote {out}')
