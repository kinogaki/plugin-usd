#!/usr/bin/env python3
"""Write src/usd/compose/flatten/schema_table.rs: every schema class of
the OpenUSD v26.08 plugins usdcat loads (their generatedSchema.usda), with
its built-in API schemas and its properties' type names, variability and
kind. Usage: tools/gen_schema_table.py <OpenUSD v26.08 checkout>.
UsdStage::Flatten takes a built-in property's type and variability
from this definition, and writes it not custom."""
import re
from pathlib import Path

import sys
ROOT = Path(__file__).resolve().parents[1]
PXR = Path(sys.argv[1]) / "pxr/usd"
OUT = ROOT / "src/usd/compose/flatten/schema_table.rs"
# The plugins the usdcat build installs (OpenUSD-install/lib/usd).
PLUGINS = ["usd", "usdGeom", "usdHydra", "usdLod", "usdLux", "usdMedia", "usdPhysics", "usdProc",
           "usdProfiles", "usdRender", "usdRi", "usdSemantics", "usdShade", "usdSkel", "usdUI", "usdVol"]

CLASS = re.compile(r'^class (?:(\w+) )?"(\w+)"')
PROPERTY = re.compile(r'^    (custom )?(uniform |varying )?([\w\[\]]+) ([\w:]+)(?:\s|$)')
REL = re.compile(r'^    (custom )?(uniform |varying )?rel ([\w:]+)(?:\s|$)')

schemas = []
for plugin in PLUGINS:
    lines = (PXR / plugin / "generatedSchema.usda").read_text().splitlines()
    at = 0
    while at < len(lines):
        match = CLASS.match(lines[at])
        if not match:
            at += 1
            continue
        name = match.group(2)
        # Metadata up to the body's opening brace.
        head = []
        at += 1
        while at < len(lines) and lines[at] != "{":
            head.append(lines[at])
            at += 1
        meta = "\n".join(head)
        builtins = []
        found = re.search(r'^    (?:prepend |append )?apiSchemas = \[([^\]]*)\]', meta, re.M)
        if found:
            builtins = re.findall(r'"([^"]+)"', found.group(1))
        properties = []
        at += 1
        while at < len(lines) and lines[at] != "}":
            line = lines[at]
            rel = REL.match(line)
            prop = PROPERTY.match(line)
            if rel:
                properties.append((rel.group(3), "rel", "r"))
            elif prop and prop.group(3) not in ("rel",):
                properties.append((prop.group(4), prop.group(3), "u" if prop.group(2) == "uniform " else "v"))
            at += 1
        # Multiple-apply schemas name their properties per instance.
        multiple = any("__INSTANCE_NAME__" in p for p, _, _ in properties)
        schemas.append((name + ("*" if multiple else ""), builtins, properties))
        at += 1

rows = []
for name, builtins, properties in schemas:
    body = ";".join(f"{p} {t} {f}" for p, t, f in properties)
    rows.append(f'    "{name}|{",".join(builtins)}|{body}",')
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(f'''//! Schema definitions, generated by tools/gen_schema_table.py from the
//! generatedSchema.usda of OpenUSD v26.08's plugins; do not edit. One entry
//! per schema class, "Name|built-in API schemas|properties". A
//! multiple-apply API schema's name ends in "*" and its property names hold
//! __INSTANCE_NAME__. Each property is "name type flag": u for uniform, v
//! for varying, r for a relationship (type "rel").

#[rustfmt::skip]
pub(super) const SCHEMA_TABLE: [&str; {len(rows)}] = [
''' + "\n".join(rows) + "\n];\n")
print(f"{len(rows)} schemas, {sum(len(p) for _, _, p in schemas)} properties -> {OUT}")
